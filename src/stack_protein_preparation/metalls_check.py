"""Metal classification and geometry checks for FRUTON prepared models.

The module inspects metal atoms in starting structures, component files,
produced FRUTON models, and prepared variants before the final workbook is written. It keeps the policy small:
standard non-transition alkali/alkaline-earth ions are treated as standard-ion
parameter cases, while transition metals are analysed geometrically and flagged
for the metal-parameter branch. Crystal waters are included in the analysis PDB
because crystallographic water molecules frequently complete metal coordination
shells and must not be ignored when deciding the local geometry.

ChimeraX support is deliberately optional. When a ChimeraX executable is found,
this module writes and runs a small contacts script so the contact analysis can
be inspected with the same external tool that a user would use manually. The
structured TSV/JSON output is still generated by deterministic Python distance
analysis, so the pipeline remains usable on machines where ChimeraX is not
installed.
"""


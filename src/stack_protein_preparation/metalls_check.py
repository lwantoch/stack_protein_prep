@dataclass(frozen=True)
class PDBAtomRecord:
    """Minimal PDB atom record used for metal-contact analysis."""

    serial: int
    record_name: str
    atom_name: str
    residue_name: str
    chain_id: str
    residue_number: int
    insertion_code: str
    element: str
    formal_charge: int | None
    x: float
    y: float
    z: float
    source_path: str
    source_role: str
    raw_line: str

    @property
    def residue_label(self) -> str:
        insertion = self.insertion_code.strip()
        return f"{self.residue_name} {self.chain_id or '<blank>'} {self.residue_number}{insertion}"

    @property
    def atom_label(self) -> str:
        return f"{self.residue_label} {self.atom_name.strip()}"


@dataclass(frozen=True)
class MetalContact:
    """One donor atom close enough to be treated as a metal contact."""

    metal_label: str
    metal_element: str
    donor_label: str
    donor_element: str
    donor_residue_name: str
    donor_chain_id: str
    donor_residue_number: int
    donor_atom_name: str
    distance_angstrom: float
    donor_source_role: str
    vector_x: float
    vector_y: float
    vector_z: float



def _angle_for_two_contacts(metal_atom: PDBAtomRecord, contacts: tuple[MetalContact, ...]) -> float:
    points = _contact_points_from_labels(metal_atom, contacts)
    if len(points) < 2:
        return 0.0
    return _angle_between_vectors(points[0], points[1])


def _is_square_planar_like(metal_atom: PDBAtomRecord, contacts: tuple[MetalContact, ...]) -> bool:
    points = _contact_points_from_labels(metal_atom, contacts)
    if len(points) != 4:
        return False
    angles = sorted(_angle_between_vectors(a, b) for a, b in itertools.combinations(points, 2))
    near_90 = sum(1 for angle in angles if 70.0 <= angle <= 110.0)
    near_180 = sum(1 for angle in angles if angle >= 150.0)
    return near_90 >= 4 and near_180 >= 1


def _has_opposite_contact_pair(
    metal_atom: PDBAtomRecord,
    contacts: tuple[MetalContact, ...],
    *,
    min_angle: float,
) -> bool:
    points = _contact_points_from_labels(metal_atom, contacts)
    return any(
        _angle_between_vectors(a, b) >= min_angle for a, b in itertools.combinations(points, 2)
    )


def _contact_points_from_labels(
    metal_atom: PDBAtomRecord,
    contacts: tuple[MetalContact, ...],
) -> list[tuple[float, float, float]]:
    """Return donor vectors centered on the metal atom."""

    return [(contact.vector_x, contact.vector_y, contact.vector_z) for contact in contacts]


def _angle_between_vectors(
    vector_a: tuple[float, float, float],
    vector_b: tuple[float, float, float],
) -> float:
    dot = sum(a * b for a, b in zip(vector_a, vector_b, strict=True))
    norm_a = math.sqrt(sum(a * a for a in vector_a))
    norm_b = math.sqrt(sum(b * b for b in vector_b))
    if norm_a == 0.0 or norm_b == 0.0:
        return 0.0
    cosine = max(-1.0, min(1.0, dot / (norm_a * norm_b)))
    return math.degrees(math.acos(cosine))


def _pdb_contains_water(pdb_path: Path) -> bool:
    return any(atom.residue_name in WATER_RESIDUE_NAMES for atom in read_pdb_atom_records(pdb_path, source_role="probe"))


def _pdb_contains_metals(pdb_path: Path) -> bool:
    return any(is_true_metal_atom(atom) for atom in read_pdb_atom_records(pdb_path, source_role="probe"))


def is_true_metal_atom(atom: PDBAtomRecord) -> bool:
    """Return whether an atom record is an actual metal ion.

    This deliberately avoids the common legacy-PDB trap where protein atom names
    such as ``HG`` (gamma hydrogen), ``CD`` (delta carbon), or ``CA`` (alpha
    carbon) are mistaken for Hg, Cd, or Ca when the element column is blank.
    Real metal atoms are accepted from explicit metal residue names, explicit
    HETATM element fields, or atom names that match the residue-level metal ion.
    """

    if atom.element not in METAL_ELEMENTS:
        return False

    residue_identity = METAL_RESIDUE_IDENTITY.get(atom.residue_name)
    if residue_identity is not None:
        return atom.element == residue_identity[0]

    if atom.record_name == "HETATM":
        atom_name = atom.atom_name.strip().upper()
        return atom_name == atom.element or atom_name.startswith(atom.element)

    return False


def _infer_element_from_pdb_fields(
    *,
    record_name: str,
    atom_name: str,
    residue_name: str,
    raw_element: str,
) -> str:
    """Infer element without misreading protein atom names as metals."""

    clean_raw_element = raw_element.strip().upper()
    clean_atom_name = "".join(character for character in atom_name.strip().upper() if character.isalpha())
    clean_residue_name = residue_name.strip().upper()
    clean_record_name = record_name.strip().upper()

    if clean_raw_element:
        return clean_raw_element

    residue_identity = METAL_RESIDUE_IDENTITY.get(clean_residue_name)
    if residue_identity is not None:
        return residue_identity[0]

    # For HETATM records only, accept exact metal-like atom names. This covers
    # stripped component files where the element column was lost. We do not use
    # this rule for ATOM records because atom names such as HG, CD, CA, and FE
    # can be ordinary protein atom names or atom-type-like labels.
    if clean_record_name == "HETATM":
        for length in (2, 1):
            candidate = clean_atom_name[:length]
            if candidate in METAL_ELEMENTS and clean_atom_name == candidate:
                return candidate

    if clean_atom_name.startswith("H"):
        return "H"

    # Common two-letter non-metal elements that can appear in protein/ligand
    # atom names and are not confused with standard protein carbon/hydrogen
    # positional labels.
    for candidate in ("CL", "BR", "SE"):
        if clean_atom_name.startswith(candidate):
            return candidate

    if clean_atom_name[:1] in {"C", "N", "O", "S", "P", "F", "I"}:
        return clean_atom_name[:1]

    return clean_atom_name[:1] if clean_atom_name else ""


def _charge_from_residue_name(residue_name: str) -> int | None:
    identity = METAL_RESIDUE_IDENTITY.get(residue_name.strip().upper())
    if identity is None:
        return None
    return identity[1]


def _parse_pdb_atom_charge(value: str) -> int | None:
    """Parse legacy PDB atom charge columns, e.g. ``2+`` or ``1-``."""

    text = value.strip()
    if not text:
        return None

    if len(text) == 2 and text[0].isdigit() and text[1] in {"+", "-"}:
        magnitude = int(text[0])
        return magnitude if text[1] == "+" else -magnitude

    if len(text) == 2 and text[1].isdigit() and text[0] in {"+", "-"}:
        magnitude = int(text[1])
        return magnitude if text[0] == "+" else -magnitude

    return None


def _ion_label_from_atom(atom: PDBAtomRecord, *, default: str) -> str:
    """Return a compact ion label using explicit or residue-derived charge."""

    charge = atom.formal_charge
    if charge is None:
        return default

    sign = "+" if charge > 0 else "-"
    magnitude = abs(charge)
    return f"{_title_case_element(atom.element)}{magnitude if magnitude != 1 else ''}{sign}"


def _transition_ion_label(atom: PDBAtomRecord) -> str:
    """Return transition-metal ion label without forcing Fe/Cu/Mn to 2+."""

    if atom.formal_charge is not None:
        sign = "+" if atom.formal_charge > 0 else "-"
        magnitude = abs(atom.formal_charge)
        return f"{_title_case_element(atom.element)}{magnitude if magnitude != 1 else ''}{sign}"

    common_unknown = {
        "FE": "Fe(unknown; often Fe2+/Fe3+)",
        "CU": "Cu(unknown; often Cu+/Cu2+)",
        "MN": "Mn(unknown; often Mn2+/Mn3+/Mn4+)",
        "CO": "Co(unknown; often Co2+/Co3+)",
        "NI": "Ni(unknown; often Ni2+)",
        "ZN": "Zn2+",
        "CD": "Cd2+",
        "HG": "Hg2+",
    }
    return common_unknown.get(atom.element, f"{_title_case_element(atom.element)}(transition; charge unknown)")


def _title_case_element(element: str) -> str:
    text = element.strip().upper()
    if len(text) <= 1:
        return text
    return text[0] + text[1:].lower()


def _safe_token(value: str) -> str:
    token = "".join(character if character.isalnum() or character in {"_", "-"} else "_" for character in value.strip())
    return token.strip("_") or "variant"


def _safe_int(value: str, *, default: int) -> int:
    try:
        return int(value)
    except Exception:
        return default


def _safe_float(value: str, *, default: float) -> float:
    try:
        return float(value)
    except Exception:
        return default


def _unique_keep_order(values: list[str] | tuple[str, ...] | set[str]) -> list[str]:
    seen: set[str] = set()
    ordered: list[str] = []
    for value in values:
        if value in seen:
            continue
        seen.add(value)
        ordered.append(value)
    return ordered
def summarize_metal_site(
    *,
    metal_atom: PDBAtomRecord,
    atom_records: list[PDBAtomRecord],
    contact_cutoff_angstrom: float,
) -> MetalSiteSummary:
    """Classify one metal atom and its coordination shell."""

    contacts = tuple(
        sorted(
            find_metal_contacts(
                metal_atom=metal_atom,
                atom_records=atom_records,
                contact_cutoff_angstrom=contact_cutoff_angstrom,
            ),
            key=lambda contact: contact.distance_angstrom,
        )
    )

    if metal_atom.element in STANDARD_NONTRANSITION_IONS:
        ion_info = STANDARD_NONTRANSITION_IONS[metal_atom.element]
        return MetalSiteSummary(
            metal_label=metal_atom.atom_label,
            element=metal_atom.element,
            ion_label=_ion_label_from_atom(metal_atom, default=str(ion_info["ion_label"])),
            metal_class="standard_nontransition",
            coordination_number=len(contacts),
            found_geometry="not_required_for_standard_ion",
            probable_geometry="not_required_for_standard_ion",
            geometry_match="n/a",
            parameter_reference=str(ion_info["parameter_reference"]),
            requires_transition_parameters=False,
            contacts=contacts,
        )

    if metal_atom.element in TRANSITION_METAL_ELEMENTS:
        found_geometry = classify_coordination_geometry(
            metal_atom=metal_atom,
            contacts=contacts,
        )
        probable_geometry_list = TRANSITION_ION_GEOMETRY_PREFERENCES.get(
            metal_atom.element,
            ["unknown"],
        )
        probable_geometry = "|".join(probable_geometry_list)
        geometry_match = "yes" if found_geometry in probable_geometry_list else "no"
        return MetalSiteSummary(
            metal_label=metal_atom.atom_label,
            element=metal_atom.element,
            ion_label=_transition_ion_label(metal_atom),
            metal_class="transition",
            coordination_number=len(contacts),
            found_geometry=found_geometry,
            probable_geometry=probable_geometry,
            geometry_match=geometry_match,
            parameter_reference="transition-metal parameters required; geometry recorded for Gaussian/RESP/CESGA branch",
            requires_transition_parameters=True,
            contacts=contacts,
        )

    return MetalSiteSummary(
        metal_label=metal_atom.atom_label,
        element=metal_atom.element,
        ion_label=metal_atom.element,
        metal_class="unsupported_nontransition",
        coordination_number=len(contacts),
        found_geometry="unsupported_ion",
        probable_geometry="unsupported_ion",
        geometry_match="n/a",
        parameter_reference="unsupported non-transition metal; explicit parameters required",
        requires_transition_parameters=False,
        contacts=contacts,
    )


def find_metal_contacts(
    *,
    metal_atom: PDBAtomRecord,
    atom_records: list[PDBAtomRecord],
    contact_cutoff_angstrom: float,
) -> list[MetalContact]:
    """Return donor atoms within the coordination cutoff around one metal."""

    contacts: list[MetalContact] = []
    for atom in atom_records:
        if atom is metal_atom:
            continue
        if is_true_metal_atom(atom):
            continue
        if atom.element not in DONOR_ELEMENTS:
            continue
        distance = distance_between_atoms(metal_atom, atom)
        if distance > contact_cutoff_angstrom:
            continue
        contacts.append(
            MetalContact(
                metal_label=metal_atom.atom_label,
                metal_element=metal_atom.element,
                donor_label=atom.atom_label,
                donor_element=atom.element,
                donor_residue_name=atom.residue_name,
                donor_chain_id=atom.chain_id,
                donor_residue_number=atom.residue_number,
                donor_atom_name=atom.atom_name,
                distance_angstrom=round(distance, 3),
                donor_source_role=atom.source_role,
                vector_x=atom.x - metal_atom.x,
                vector_y=atom.y - metal_atom.y,
                vector_z=atom.z - metal_atom.z,
            )
        )
    return contacts


def classify_coordination_geometry(
    *,
    metal_atom: PDBAtomRecord,
    contacts: tuple[MetalContact, ...],
) -> str:
    """Classify a transition-metal site with conservative geometric heuristics."""

    coordination_number = len(contacts)
    if coordination_number == 0:
        return "uncoordinated"
    if coordination_number == 1:
        return "monodentate_contact"
    if coordination_number == 2:
        angle = _angle_for_two_contacts(metal_atom, contacts)
        return "linear" if angle >= 150.0 else "bent"
    if coordination_number == 3:
        return "trigonal_planar"
    if coordination_number == 4:
        if _is_square_planar_like(metal_atom, contacts):
            return "square_planar"
        return "tetrahedral"
    if coordination_number == 5:
        if _has_opposite_contact_pair(metal_atom, contacts, min_angle=155.0):
            return "trigonal_bipyramidal"
        return "square_pyramidal"
    if coordination_number == 6:
        return "octahedral"
    if coordination_number == 7:
        return "pentagonal_bipyramidal_or_capped_octahedral"
    return f"high_coordination_{coordination_number}"


def read_pdb_atom_records(pdb_path: str | Path, *, source_role: str) -> list[PDBAtomRecord]:
    """Read ATOM/HETATM records with Gemmi first and legacy parsing as fallback.

    Gemmi is preferred because it understands the PDB/mmCIF structure hierarchy,
    element objects, heterogen flags, residue identity, and atom coordinates
    without relying on fragile atom-name heuristics. This avoids the common
    legacy-PDB error where protein atom names such as ``HG``, ``CD``, or ``CA``
    are read as Hg, Cd, or Ca. The fallback parser remains available for
    environments where Gemmi is not installed, but the normal FRUTON environment
    should use Gemmi.
    """

    path = Path(pdb_path)

    try:
        return _read_atom_records_with_gemmi(path, source_role=source_role)
    except Exception:
        return _read_atom_records_from_pdb_lines(path, source_role=source_role)


def _read_atom_records_with_gemmi(pdb_path: Path, *, source_role: str) -> list[PDBAtomRecord]:
    """Read atom records through Gemmi while preserving FRUTON's flat record type."""

    import gemmi

    structure = gemmi.read_structure(str(pdb_path))
    atom_records: list[PDBAtomRecord] = []

    for model in structure:
        for chain in model:
            for residue in chain:
                record_name = "HETATM" if str(residue.het_flag).upper() == "H" else "ATOM"
                insertion_code = "" if str(residue.seqid.icode).strip() == "?" else str(residue.seqid.icode).strip()

                for atom in residue:
                    element = str(atom.element.name).upper()
                    if element == "D":
                        element = "H"

                    formal_charge = int(atom.charge) if int(atom.charge) != 0 else None
                    if formal_charge is None:
                        formal_charge = _charge_from_residue_name(str(residue.name).strip().upper())

                    atom_records.append(
                        PDBAtomRecord(
                            serial=int(atom.serial) if int(atom.serial) else 0,
                            record_name=record_name,
                            atom_name=str(atom.name).strip(),
                            residue_name=str(residue.name).strip().upper(),
                            chain_id=str(chain.name).strip(),
                            residue_number=int(residue.seqid.num) if residue.seqid.num is not None else 0,
                            insertion_code=insertion_code,
                            element=element,
                            formal_charge=formal_charge,
                            x=float(atom.pos.x),
                            y=float(atom.pos.y),
                            z=float(atom.pos.z),
                            source_path=str(pdb_path),
                            source_role=source_role,
                            raw_line="",
                        )
                    )

    return atom_records


def _read_atom_records_from_pdb_lines(pdb_path: Path, *, source_role: str) -> list[PDBAtomRecord]:
    """Read ATOM/HETATM records from fixed-width PDB lines as a fallback."""

    atom_records: list[PDBAtomRecord] = []
    with pdb_path.open("r", encoding="utf-8", errors="replace") as handle:
        for raw_line in handle:
            line = raw_line.rstrip("\n")
            if not (line.startswith("ATOM  ") or line.startswith("HETATM")):
                continue
            atom_records.append(_parse_pdb_atom_line(line, source_path=pdb_path, source_role=source_role))
    return atom_records


def distance_between_atoms(atom_a: PDBAtomRecord, atom_b: PDBAtomRecord) -> float:
    """Return Euclidean distance between two parsed PDB atom records."""

    dx = atom_a.x - atom_b.x
    dy = atom_a.y - atom_b.y
    dz = atom_a.z - atom_b.z
    return math.sqrt(dx * dx + dy * dy + dz * dz)


def _write_analysis_pdb(
    *,
    model_pdb_path: Path,
    output_pdb_path: Path,
    water_pdb_path: Path | None,
    metals_pdb_path: Path | None,
) -> None:
    """Write analysis PDB with crystal waters and metals available."""

    section_paths = [model_pdb_path]
    if water_pdb_path is not None and water_pdb_path.exists() and not _pdb_contains_water(model_pdb_path):
        section_paths.append(water_pdb_path)
    if metals_pdb_path is not None and metals_pdb_path.exists() and not _pdb_contains_metals(model_pdb_path):
        section_paths.append(metals_pdb_path)

    output_pdb_path.parent.mkdir(parents=True, exist_ok=True)
    atom_serial = 1
    with output_pdb_path.open("w", encoding="utf-8") as output_handle:
        for section_path in section_paths:
            with section_path.open("r", encoding="utf-8", errors="replace") as input_handle:
                for raw_line in input_handle:
                    line = raw_line.rstrip("\n")
                    if line.startswith("ATOM  ") or line.startswith("HETATM"):
                        output_handle.write(f"{line[:6]}{atom_serial:>5}{line[11:]}\n")
                        atom_serial += 1
            output_handle.write("TER\n")
        output_handle.write("END\n")


def _parse_pdb_atom_line(line: str, *, source_path: Path, source_role: str) -> PDBAtomRecord:
    """Parse the subset of a PDB ATOM/HETATM line needed here."""

    atom_name = line[12:16].strip()
    residue_name = line[17:20].strip().upper()
    chain_id = line[21:22].strip()
    insertion_code = line[26:27].strip()
    record_name = line[0:6].strip()
    formal_charge = _parse_pdb_atom_charge(line[78:80] if len(line) >= 80 else "")
    raw_element = line[76:78].strip().upper() if len(line) >= 78 else ""
    element = _infer_element_from_pdb_fields(
        record_name=record_name,
        atom_name=atom_name,
        residue_name=residue_name,
        raw_element=raw_element,
    )
    if formal_charge is None:
        formal_charge = _charge_from_residue_name(residue_name)
    return PDBAtomRecord(
        serial=_safe_int(line[6:11], default=0),
        record_name=record_name,
        atom_name=atom_name,
        residue_name=residue_name,
        chain_id=chain_id,
        residue_number=_safe_int(line[22:26], default=0),
        insertion_code=insertion_code,
        element=element,
        formal_charge=formal_charge,
        x=_safe_float(line[30:38], default=0.0),
        y=_safe_float(line[38:46], default=0.0),
        z=_safe_float(line[46:54], default=0.0),
        source_path=str(source_path),
        source_role=source_role,
        raw_line=line,
    )


def _run_chimera_contact_script(
    *,
    analysis_input_path: Path,
    output_dir: Path,
    pdb_id: str,
    variant_label: str,
    chimera_executable: str | None,
    contact_cutoff_angstrom: float,
) -> dict[str, Path | str | None]:
    """Run a minimal ChimeraX contacts script when ChimeraX is available."""

    executable = chimera_executable or shutil.which("chimerax") or shutil.which("ChimeraX")
    script_path = output_dir / f"{pdb_id}_{variant_label}_chimera_contacts.cxc"
    log_path = output_dir / f"{pdb_id}_{variant_label}_chimera_contacts.log"

    script_text = "\n".join(
        [
            f"open {analysis_input_path}",
            "delete solvent false",
            f"contacts @MN,FE,CO,NI,CU,ZN,CD,HG,CR,V,MO,W restrict @N*,O*,S*,SE* distance {contact_cutoff_angstrom:.2f} reveal true name metal_contacts color gold",
            "save {0}".format(output_dir / f"{pdb_id}_{variant_label}_chimera_session.cxs"),
            "exit",
            "",
        ]
    )
    script_path.write_text(script_text, encoding="utf-8")

    if executable is None:
        log_path.write_text("ChimeraX executable not found; Python contact analysis used.\n", encoding="utf-8")
        return {"script_path": script_path, "log_path": log_path, "status": "missing_executable"}

    try:
        completed = subprocess.run(
            [executable, "--nogui", str(script_path)],
            check=False,
            capture_output=True,
            text=True,
            timeout=180,
        )
    except Exception as error:
        log_path.write_text(f"ChimeraX execution failed: {error!r}\n", encoding="utf-8")
        return {"script_path": script_path, "log_path": log_path, "status": "failed"}

    log_path.write_text(
        completed.stdout + "\n" + completed.stderr,
        encoding="utf-8",
    )
    return {
        "script_path": script_path,
        "log_path": log_path,
        "status": "success" if completed.returncode == 0 else f"returncode_{completed.returncode}",
    }


def _write_contacts_tsv(path: Path, contacts: tuple[MetalContact, ...] | list[MetalContact]) -> None:
    """Write contacts as a compact TSV for manual inspection."""

    path.parent.mkdir(parents=True, exist_ok=True)
    header = [
        "metal_label",
        "metal_element",
        "donor_label",
        "donor_element",
        "donor_residue_name",
        "donor_chain_id",
        "donor_residue_number",
        "donor_atom_name",
        "distance_angstrom",
        "donor_source_role",
        "vector_x",
        "vector_y",
        "vector_z",
    ]
    with path.open("w", encoding="utf-8") as handle:
        handle.write("\t".join(header) + "\n")
        for contact in contacts:
            handle.write(
                "\t".join(
                    [
                        contact.metal_label,
                        contact.metal_element,
                        contact.donor_label,
                        contact.donor_element,
                        contact.donor_residue_name,
                        contact.donor_chain_id,
                        str(contact.donor_residue_number),
                        contact.donor_atom_name,
                        f"{contact.distance_angstrom:.3f}",
                        contact.donor_source_role,
                        f"{contact.vector_x:.3f}",
                        f"{contact.vector_y:.3f}",
                        f"{contact.vector_z:.3f}",
                    ]
                )
                + "\n"
            )


